    private void validateKey(java.awt.event.KeyEvent evt, javax.swing.JTextField field) {
        char c = evt.getKeyChar();

        boolean isDigit = Character.isDigit(c);
        boolean isControl = (c == '\b' || c == '\u007f'); // backspace and delete

        if (!(isDigit || isControl)) {
            evt.consume();
            JOptionPane.showMessageDialog(this, "Please enter numbers only.",
                    "Invalid input", JOptionPane.ERROR_MESSAGE);
            return;
        }

        int max = (field == birthYearTextField) ? 4 : 2;
        if (isDigit && field.getText().length() >= max) {
            evt.consume();
        }
    }


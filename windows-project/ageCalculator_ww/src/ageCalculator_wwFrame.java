    private void calculateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateBtnActionPerformed

        if (birthDayTextField.getText().trim().isEmpty()
                || birthMonthTextField.getText().trim().isEmpty()
                || birthYearTextField.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                    "Kindly fill in all your birth date fields.",
                    "Missing Information",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }
        int day = Integer.parseInt(birthDayTextField.getText());
        int month = Integer.parseInt(birthMonthTextField.getText());
        int year = Integer.parseInt(birthYearTextField.getText());

        LocalDate birthDate = LocalDate.of(year, month, day);
        LocalDate today = LocalDate.now();

        if (birthDate.isAfter(today)) {
            JOptionPane.showMessageDialog(this,
                    "Invalid Birthday! Date of birth cannot be in the future.",
                    "Invalid Date",
                    JOptionPane.ERROR_MESSAGE);

            return;
        }
        if (birthDayTextField.getText().isEmpty()
                || birthMonthTextField.getText().isEmpty()
                || birthYearTextField.getText().isEmpty()) {
            JOptionPane.showMessageDialog(
                    this,
                    "Please fill in all the fields.",
                    "error",
                    JOptionPane.ERROR_MESSAGE
            );
            return;
        }

        int birthDay = Integer.parseInt(birthDayTextField.getText());
        int birthMonth = Integer.parseInt(birthMonthTextField.getText());
        int birthYear = Integer.parseInt(birthYearTextField.getText());

        int currentDay = today.getDayOfMonth();
        int currentMonth = today.getMonthValue();
        int currentYear = today.getYear();

        int days = currentDay - birthDay;
        int months = currentMonth - birthMonth;
        int years = currentYear - birthYear;

        if (days < 0) {
            days = days + today.minusMonths(1).lengthOfMonth();
            months = months - 1;
        }

        if (months < 0) {
            months = months + 12;
            years = years - 1;
        }

        yearsTextField.setText(String.valueOf(years));
        monthsTextField.setText(String.valueOf(months));
        daysTextField.setText(String.valueOf(days));


    }//GEN-LAST:event_calculateBtnActionPerformed


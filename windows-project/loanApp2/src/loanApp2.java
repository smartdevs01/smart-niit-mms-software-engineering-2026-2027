    private void applyInputFilters() {

    ((javax.swing.text.AbstractDocument) loanAmount.getDocument())
            .setDocumentFilter(new NumericDocumentFilter(true));

    ((javax.swing.text.AbstractDocument) loanDuration.getDocument())
            .setDocumentFilter(new NumericDocumentFilter(false));
}
    private class NumericDocumentFilter
        extends javax.swing.text.DocumentFilter {

    private final boolean allowDecimal;

    public NumericDocumentFilter(boolean allowDecimal) {
        this.allowDecimal = allowDecimal;
    }

    @Override
    public void insertString(
            javax.swing.text.DocumentFilter.FilterBypass fb,
            int offset,
            String text,
            javax.swing.text.AttributeSet attr)
            throws javax.swing.text.BadLocationException {

        if (text != null) {
            replace(fb, offset, 0, text, attr);
        }
    }

    @Override
    public void replace(
            javax.swing.text.DocumentFilter.FilterBypass fb,
            int offset,
            int length,
            String text,
            javax.swing.text.AttributeSet attrs)
            throws javax.swing.text.BadLocationException {

        if (text == null) {
            return;
        }

        javax.swing.text.Document doc = fb.getDocument();

        String current = doc.getText(0, doc.getLength());

        String updated = current.substring(0, offset)
                + text
                + current.substring(offset + length);

        String pattern = allowDecimal
                ? "\\d*(\\.\\d*)?"
                : "\\d{0,2}";

        if (updated.matches(pattern)) {
            fb.replace(offset, length, text, attrs);
        }
    }
}


private void configureInputSequence() {

    // Disable the duration field initially
    loanDuration.setEnabled(false);

    // Monitor changes in the loan amount field
    loanAmount.getDocument().addDocumentListener(
            new javax.swing.event.DocumentListener() {

        @Override
        public void insertUpdate(javax.swing.event.DocumentEvent e) {
            checkLoanAmount();
        }

        @Override
        public void removeUpdate(javax.swing.event.DocumentEvent e) {
            checkLoanAmount();
        }

        @Override
        public void changedUpdate(javax.swing.event.DocumentEvent e) {
            checkLoanAmount();
        }
    });
}

private void checkLoanAmount() {

    String amountText = loanAmount.getText().trim();

    boolean validAmount = false;

    try {
        double amount = Double.parseDouble(amountText);

        validAmount = !amountText.isEmpty()
                && Double.isFinite(amount)
                && amount > 0;

    } catch (NumberFormatException e) {
        validAmount = false;
    }

    // Enable duration only when the amount is valid
    loanDuration.setEnabled(validAmount);

    // Clear duration if the loan amount becomes invalid
    if (!validAmount) {
        loanDuration.setText("");
    }
}


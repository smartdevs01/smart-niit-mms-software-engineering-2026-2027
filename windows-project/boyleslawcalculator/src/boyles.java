    private void calculateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateActionPerformed
       try {

        double ans;

        switch (choice1.getSelectedIndex()) {

            case 0: // Find P1

                double p2 = getPositiveValue(inip4, "P2");
                double v2 = getPositiveValue(iniv4, "V2");
                double v1 = getPositiveValue(iniv3, "V1");

                ans = (p2 * v2) / v1;

                result1.setText(String.format(
                        java.util.Locale.US,
                        "P1 = %.2f", ans));

                break;

            case 1: // Find V1

                double p2v1 = getPositiveValue(inip4, "P2");
                double v2v1 = getPositiveValue(iniv4, "V2");
                double p1v1 = getPositiveValue(inip3, "P1");

                ans = (p2v1 * v2v1) / p1v1;

                result1.setText(String.format(
                        java.util.Locale.US,
                        "V1 = %.2f", ans));

                break;

            case 2: // Find P2

                double p1 = getPositiveValue(inip3, "P1");
                double v1p2 = getPositiveValue(iniv3, "V1");
                double v2p2 = getPositiveValue(iniv4, "V2");

                ans = (p1 * v1p2) / v2p2;

                result1.setText(String.format(
                        java.util.Locale.US,
                        "P2 = %.2f", ans));

                break;

            case 3: // Find V2

                double p1v2 = getPositiveValue(inip3, "P1");
                double v1v2 = getPositiveValue(iniv3, "V1");
                double p2v2 = getPositiveValue(inip4, "P2");

                ans = (p1v2 * v1v2) / p2v2;

                result1.setText(String.format(
                        java.util.Locale.US,
                        "V2 = %.2f", ans));

                break;

            default:
                throw new IllegalArgumentException(
                        "Please select a variable to calculate."
                );
        }

        if (!Double.isFinite(ans) || ans <= 0) {
            throw new ArithmeticException(
                    "The calculated result is outside the valid range."
            );
        }

    } catch (IllegalArgumentException | ArithmeticException e) {

        result1.setText("");

        JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Input Validation Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_calculateActionPerformed


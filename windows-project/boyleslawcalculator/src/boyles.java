private double getPositiveValue(
        JTextField field, String variableName) {

    String input = field.getText().trim();

    if (input.isEmpty()) {
        throw new IllegalArgumentException(
                variableName + " is required."
        );
    }

    double value;

    try {
        value = Double.parseDouble(input);
    } catch (NumberFormatException e) {
        throw new IllegalArgumentException(
                variableName + " must be a valid number."
        );
    }

    if (!Double.isFinite(value) || value <= 0) {
        throw new IllegalArgumentException(
                variableName + " must be greater than zero."
        );
    }

    return value;
}


private void installNumericFilter(JTextField field) {

    AbstractDocument document =
            (AbstractDocument) field.getDocument();

    document.setDocumentFilter(new DocumentFilter() {

        private boolean isValidInput(String text) {
            return text.matches("\\d{0,9}(\\.\\d{0,6})?");
        }

        private void showInvalidInputMessage() {
            JOptionPane.showMessageDialog(
                    boyles.this,
                    "Invalid input! Please enter numbers only.",
                    "Invalid Input",
                    JOptionPane.ERROR_MESSAGE
            );
        }

        @Override
        public void insertString(
                FilterBypass fb,
                int offset,
                String text,
                AttributeSet attr) throws BadLocationException {

            replace(fb, offset, 0, text, attr);
        }

        @Override
        public void replace(
                FilterBypass fb,
                int offset,
                int length,
                String text,
                AttributeSet attrs) throws BadLocationException {

            String currentText = fb.getDocument().getText(
                    0, fb.getDocument().getLength()
            );

            String newText = text == null ? "" : text;

            String updatedText =
                    currentText.substring(0, offset)
                    + newText
                    + currentText.substring(offset + length);

            if (isValidInput(updatedText)) {

                fb.replace(offset, length, newText, attrs);

            } else {

                showInvalidInputMessage();
            }
        }
    });
}



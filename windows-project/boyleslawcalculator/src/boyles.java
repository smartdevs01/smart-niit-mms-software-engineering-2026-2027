    private void choice1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_choice1ActionPerformed
         java.awt.Color normalColor = java.awt.Color.WHITE;
    java.awt.Color lockedColor = new java.awt.Color(132, 156, 195);

    // Restore all fields first
    inip3.setEditable(true);
    inip4.setEditable(true);
    iniv3.setEditable(true);
    iniv4.setEditable(true);

    inip3.setEnabled(true);
    inip4.setEnabled(true);
    iniv3.setEnabled(true);
    iniv4.setEnabled(true);

    inip3.setBackground(normalColor);
    inip4.setBackground(normalColor);
    iniv3.setBackground(normalColor);
    iniv4.setBackground(normalColor);

    // Lock the selected field
    switch (choice1.getSelectedIndex()) {

        case 0: // Find P1
            inip3.setEditable(false);
            inip3.setEnabled(false);
            inip3.setBackground(lockedColor);
            inip3.setText("");
            break;

        case 1: // Find V1
            iniv3.setEditable(false);
            iniv3.setEnabled(false);
            iniv3.setBackground(lockedColor);
            iniv3.setText("");
            break;

        case 2: // Find P2
            inip4.setEditable(false);
            inip4.setEnabled(false);
            inip4.setBackground(lockedColor);
            inip4.setText("");
            break;

        case 3: // Find V2
            iniv4.setEditable(false);
            iniv4.setEnabled(false);
            iniv4.setBackground(lockedColor);
            iniv4.setText("");
            break;
    }

    result1.setText("");
    }//GEN-LAST:event_choice1ActionPerformed


    private void calculate1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculate1ActionPerformed
        try {
        int selection = choice1.getSelectedIndex();
        double ans;

        switch (selection) {

            case 0: // Find P1
                double p2 = Double.parseDouble(inip4.getText().trim());
                double v2 = Double.parseDouble(iniv4.getText().trim());
                double v1 = Double.parseDouble(iniv3.getText().trim());

                if (v1 == 0) {
                    throw new ArithmeticException("V1 cannot be zero.");
                }

                ans = (p2 * v2) / v1;
                result1.setText(String.format("P1 = %.2f", ans));
                break;

            case 1: // Find V1
                double p2Value = Double.parseDouble(inip4.getText().trim());
                double v2Value = Double.parseDouble(iniv4.getText().trim());
                double p1Value = Double.parseDouble(inip3.getText().trim());

                if (p1Value == 0) {
                    throw new ArithmeticException("P1 cannot be zero.");
                }

                ans = (p2Value * v2Value) / p1Value;
                result1.setText(String.format("V1 = %.2f", ans));
                break;

            case 2: // Find P2
                double p1 = Double.parseDouble(inip3.getText().trim());
                double v1Value = Double.parseDouble(iniv3.getText().trim());
                double v2Valu = Double.parseDouble(iniv4.getText().trim());

                if (v2Valu == 0) {
                    throw new ArithmeticException("V2 cannot be zero.");
                }

                ans = (p1 * v1Value) / v2Valu;
                result1.setText(String.format("P2 = %.2f", ans));
                break;

            case 3: // Find V2
                double p1Value2 = Double.parseDouble(inip3.getText().trim());
                double v1Value2 = Double.parseDouble(iniv3.getText().trim());
                double p2Value2 = Double.parseDouble(inip4.getText().trim());

                if (p2Value2 == 0) {
                    throw new ArithmeticException("P2 cannot be zero.");
                }

                ans = (p1Value2 * v1Value2) / p2Value2;
                result1.setText(String.format("V2 = %.2f", ans));
                break;
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "firstly fill the empty text field.",
            "Input invalid",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );

    } catch (ArithmeticException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            e.getMessage(),
            "Calculation Error",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_calculate1ActionPerformed

